/// Defines available navigation pages for the web player settings menu.
enum PlayerWebSettingsPage {
  /// The root settings menu listing all categories.
  root,

  /// Subtitles selection page.
  subtitles,

  /// Video resolution and quality selection page.
  quality,

  /// Audio track selection page.
  audioTracks,

  /// Playback speed selection page.
  playbackSpeed,
}
